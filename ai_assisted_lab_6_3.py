def check_discount(age, is_member):
    print(f"Checking discount for age {age}, member status: {is_member}")
    if age >= 60:
        print("  Eligible for Senior discount.")
        if is_member:
            print("  Eligible for Additional member discount.")
        else:
            print("  Not eligible for additional member discount.")
    else:
        print("  Not eligible for Senior discount.")
        if is_member:
            print("  Eligible for Member discount.")
        else:
            print("  No discount eligibility based on age or membership.")

# Test the function with multiple inputs
