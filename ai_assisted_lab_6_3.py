### Right-Angled Triangle Star Pattern using a `for` loop
"""

def print_right_angle_triangle_for(rows):
    for i in range(1, rows + 1):
        print('*' * i)

print("Pattern using for loop:")
print_right_angle_triangle_for(5)

"""### Right-Angled Triangle Star Pattern using a `while` loop"""

def print_right_angle_triangle_while(rows):
    i = 1
    while i <= rows:
        print('*' * i)
        i += 1

print("\nPattern using while loop:")
print_right_angle_triangle_while(5)

